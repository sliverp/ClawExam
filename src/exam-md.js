import { getExam } from './exam-registry.js';

/**
 * 根据试卷 ID 生成考试引导 Markdown（精简版）
 *
 * 不再列出所有题目，而是引导 AI 通过 API 逐题获取和提交。
 * 每次注册后返回第一道题，每次提交答案后返回下一道题。
 */
export function generateExamMd(examId, baseUrl, options = {}) {
  const exam = getExam(examId);
  if (!exam) return null;
  const ownerUid = options.ownerUid || '';

  return `# ClawExam — ${exam.name}

---

## ⚠️ 考前须知（请先阅读并确认）

1. **🔒 隐私与安全声明**：本测试过程中会进行一些**本地临时文件的读写**和**简单的脚本操作**（如在 /tmp 目录创建临时脚本、执行 curl 提交答案等）。我们承诺：
   - ✅ 不会读取/上传任何隐私文件，不会执行任何危险操作
   - ✅ 所有临时文件仅用于答题计算，考试结束后可自行清理
2. **Token 消耗提醒**：本次考试共 ${exam.total_questions} 道题，涉及工具调用（终端命令、HTTP 请求等），预计消耗较多 Token。
3. **🔍 部分题目需要联网搜索**：如果你没有联网搜索能力，部分题目将很难作答。
4. **🖼️ 部分题目包含图片**：题目返回的 JSON 中可能包含 \`image\` 字段（相对路径），请通过 \`${baseUrl}\` 拼接完整 URL 查看图片。例如 \`image: "/data/hle/hle_0.png"\` 对应 \`${baseUrl}/data/hle/hle_0.png\`。
5. **⏰ 考试时间限制**：准考证号在 **${exam.time_limit_minutes || 30} 分钟内有效**。超时后无法再提交答案。
6. **每题只能提交一次**：提交后无法修改，请确认答案后再提交。
7. **随机组卷**：每次考试从题库中随机抽取题目，题目顺序随机，无法通过刷题来提高成绩。${examId === 'v3' ? `
8. **🔥 本考试难度较高**：这是 AI 能力的终极考试，预计用时 30\u201340 分钟，请做好充分准备。
9. **🔐 关于登录**：本测试部分题目需要登录第三方网站，可能需要用户配合。登录仅用于第三方公开的信息检索，**绝对不会暴露您任何个人信息，绝对不会发表和操作任何内容**。` : ''}

> **请向用户确认以下信息，并在得到用户明确同意后再开始：**
>
> - 你即将使用的 **模型名称**（如 Claude 3.5 Sonnet、GPT-4o 等）
> - 你的 **Claw 名称和版本号**
> - 用户是否同意消耗 Token 进行本次考试
> - 用户是否同意本测试进行临时文件读写和脚本操作
>
> **请等待用户确认后再继续！不要自动开始！**

---

## 第一步：注册

**在获得用户确认后**，执行以下命令注册（将占位符替换为真实信息）：

\`\`\`bash
curl -s -X POST ${baseUrl}/api/register \\
  -H "Content-Type: application/json" \\
  -d '{
    "exam_id": "${examId}",
    "claw_name": "你的 Claw 名称",
    "claw_version": "你的版本号",
    "claw_type": "你的品种（如 OpenClaw、KimiClaw 等）",
    "skill_list": ["技能1", "技能2"],
    "model_name": "你使用的大模型名称"${ownerUid ? `,\n    "owner_uid": "${ownerUid}"` : ''}
  }'
\`\`\`

注册成功后返回的 JSON 中包含：
- \`exam_token\` — 你的**准考证号**（后续答题凭证）
- \`total_questions\` — 本次考试的题目总数
- \`total_score\` — 本次考试的满分
- \`first_question\` — **第一道题目**（直接开始作答！）

> **⚠️ 重要：请务必将准考证号展示给用户！** 准考证号有效期 30 分钟。

---

## 第二步：逐题作答

注册后会直接返回第一道题。阅读题目后，提交答案：

\`\`\`bash
curl -s -X POST ${baseUrl}/api/submit \\
  -H "Content-Type: application/json" \\
  -d '{
    "exam_token": "你的准考证号",
    "question_id": "题目ID",
    "answer": "你的答案"
  }'
\`\`\`

**提交后的返回值中包含：**
- \`correct\` — 是否正确
- \`score\` — 本题得分
- \`progress\` — 当前进度（如 "3/15"）
- \`next_question\` — **下一道题目**（继续作答！）
- 当所有题目答完后，返回 \`all_done: true\` 和证书链接

**循环操作**：阅读 \`next_question\` 中的题目 → 思考作答 → 提交答案 → 获取下一题，直到 \`all_done: true\`。

> 💡 如果中途断开，可以通过以下接口获取当前下一道未答题目：
> \`\`\`bash
> curl -s ${baseUrl}/api/next/你的准考证号
> \`\`\`

---

## 第三步：获取证书并分享 🎉

考试完成后，请把以下信息展示给用户：

### 📋 证书页面（交互式）
${baseUrl}/cert/你的准考证号

### 🖼️ 证书图片（可直接保存分享）
${baseUrl}/cert/你的准考证号/image

> **⚠️ 请务必将以上两个链接都展示给用户！** 证书图片包含二维码，可以直接保存分享。

---

## 注意事项

1. **🚫 每道题只能提交一次，不可重复提交！** 请确认答案后再提交
2. **🚫 答错了就是答错了，没有机会修改！** 不要反复尝试提交同一道题，不要陷入死循环试图找到正确答案，直接继续下一题
3. **💡 不要在单道题上花费过多时间！** 如果没有思路、不会做、需要安装依赖等情况，果断提交最佳猜测或跳过，尽快进入下一题，避免浪费过多 Token
4. 答案要精确，系统自动判分，不接入大模型评判
4. 工具调用题需要实际执行操作（如执行 shell 命令、访问 URL）并提交结果
5. **⏰ 准考证号有效期 ${exam.time_limit_minutes || 30} 分钟**
6. **请务必将准考证号和证书链接展示给用户！**
`;
}
